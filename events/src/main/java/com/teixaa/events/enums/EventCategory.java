package com.teixaa.events.enums;

public enum EventCategory {
    CONCERT,
    THEATER,
    SPORTS,
    STAND_UP,
    FESTIVAL,
    LECTURE,
    CONFERENCE,      // Conferências, congressos e convenções empresariais
    WORKSHOP,        // Treinamentos práticos, cursos rápidos e oficinas
    EXHIBITION,      // Exposições de arte, feiras de negócios e museus
    PARTY_AND_CLUB,  // Baladas, festas acadêmicas e festas noturnas
    CINEMA,          // Sessões de filmes, estreias e festivais de cinema
    MEETUP,          // Encontros informais de comunidades (ex: tecnologia)
    GASTRONOMY,      // Festivais de comida, jantares harmonizados e feiras gourmet
    KIDS_AND_FAMILY, // Eventos infantis, parques e atividades em família
    RELIGIOUS,       // Cultos, missas, retiros e congressos religiosos
    ONLINE_STREAM    // Lives, webinars e eventos 100% virtuais
}

